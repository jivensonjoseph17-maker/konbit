def main() -> None:
    for lang, values in T.items():
        assert len(values) == len(KEYS), f"{lang}: {len(values)} tradiksyon pou {len(KEYS)} kle"

    for lang in ["ht", *T.keys()]:
        path = HERE / f"{lang}.json"
        if not path.exists():
            print(f"{lang:>3}: pa gen {path.name} — sote")
            continue
        entries = dict(zip(KEYS, KEYS)) if lang == "ht" else dict(zip(KEYS, T[lang]))
        data = json.loads(path.read_text(encoding="utf-8"))
        added = 0
        for key, value in entries.items():
            if not data.get(key):
                data[key] = value
                added += 1
        path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"{lang:>3}: {added} fraz ajoute")


